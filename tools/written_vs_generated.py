"""How many of the matched game functions were WRITTEN and how many generated.

    python tools/written_vs_generated.py

A count of matched functions that mixes the two says something flattering
and false: 300-odd of them are one of five machine-recognised shapes, and
a generator emitting a hundred `GetTypeID`s is not a hundred functions of
decompiling. The split is decided by the banner in the source file that
defines them, so it cannot drift from what is actually in the tree.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPORT = ROOT / "build/R8IE78/report.json"
BANNERS = ("// GENERATED by tools/gen_accessors.py",
           "// GENERATED by tools/gen_typeids.py")


def main():
    if not REPORT.exists():
        sys.exit("written_vs_generated: %s is missing -- run ninja first."
                 % REPORT)
    rep = json.loads(REPORT.read_text(encoding="utf-8"))

    gen_units, gen_fn, gen_bytes = 0, 0, 0
    wr_units, wr_fn, wr_bytes = 0, 0, 0
    no_source = 0
    for u in rep["units"]:
        meta = u.get("metadata", {})
        if "game" not in (meta.get("progress_categories") or []):
            continue
        m = u.get("measures", {})
        n = m.get("matched_functions", 0)
        b = int(m.get("matched_code", 0) or 0)
        if not n:
            continue
        name = u["name"].split("/", 1)[1] if "/" in u["name"] else u["name"]
        src = None
        for ext in (".cpp", ".cxx", ".c", ""):
            p = ROOT / "src" / (name + ext)
            if p.exists():
                src = p
                break
        if src is None:
            no_source += 1
            continue
        head = src.read_text(encoding="utf-8", errors="ignore")[:200]
        if any(x in head for x in BANNERS):
            gen_units, gen_fn, gen_bytes = gen_units + 1, gen_fn + n, \
                gen_bytes + b
        else:
            wr_units, wr_fn, wr_bytes = wr_units + 1, wr_fn + n, wr_bytes + b

    cat = next(c for c in rep["categories"] if c["name"] == "Game Code")
    tot_b = int(cat["measures"]["matched_code"])
    tot_f = cat["measures"]["matched_functions"]
    all_b = int(cat["measures"]["total_code"])

    print("  Game Code %d of %d bytes (%.4f%%), %d of %d function(s)"
          % (tot_b, all_b, 100.0 * tot_b / all_b, tot_f,
             cat["measures"]["total_functions"]))
    print("")
    print("  %-12s %-8s %-10s %s" % ("", "UNITS", "FUNCTIONS", "BYTES"))
    print("  %-12s %-8d %-10d %d" % ("written", wr_units, wr_fn, wr_bytes))
    print("  %-12s %-8d %-10d %d" % ("generated", gen_units, gen_fn,
                                     gen_bytes))
    if no_source:
        print("  %-12s %-8d %-10s %s"
              % ("no source", no_source, "?", "?  -- matched with no file "
                 "in src/, which should not happen"))
    if wr_fn + gen_fn != tot_f or wr_bytes + gen_bytes != tot_b:
        sys.exit("written_vs_generated: the two halves come to %d function(s)"
                 " and %d byte(s), the category says %d and %d -- the split "
                 "does not account for everything and must not be reported."
                 % (wr_fn + gen_fn, wr_bytes + gen_bytes, tot_f, tot_b))
    return 0


if __name__ == "__main__":
    sys.exit(main())
